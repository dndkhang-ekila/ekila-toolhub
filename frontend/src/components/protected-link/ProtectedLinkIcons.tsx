export function getPasswordStrengthInfo(rawPassword: string): {
  level: 0 | 1 | 2 | 3;
  label: string;
  barColor: string;
  textColor: string;
} {
  const trimmed = rawPassword.trim();
  if (!trimmed) {
    return {
      level: 0,
      label: '',
      barColor: 'bg-neutral-200 dark:bg-neutral-800',
      textColor: 'text-neutral-400',
    };
  }
  if (trimmed.length < 4) {
    return {
      level: 1,
      label: `Cần tối thiểu 4 ký tự (thiếu ${4 - trimmed.length})`,
      barColor: 'bg-rose-500',
      textColor: 'text-rose-500',
    };
  }

  const hasLettersAndDigits = /[a-zA-Z]/.test(trimmed) && /\d/.test(trimmed);
  const hasSpecial = /[^a-zA-Z0-9]/.test(trimmed);

  if (trimmed.length >= 8 && (hasLettersAndDigits || hasSpecial)) {
    return {
      level: 3,
      label: 'Độ bảo mật tốt',
      barColor: 'bg-emerald-500',
      textColor: 'text-emerald-600 dark:text-emerald-400',
    };
  }

  return {
    level: 2,
    label: 'Hợp lệ (khuyên dùng >= 8 ký tự gồm chữ & số)',
    barColor: 'bg-amber-500',
    textColor: 'text-amber-600 dark:text-amber-400',
  };
}

/**
 * Sao chép chuỗi vào clipboard kèm fallback tương thích mọi trình duyệt.
 */
export async function copyTextToClipboard(text: string): Promise<boolean> {
  if (!text || typeof window === 'undefined') return false;
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Fallback sang execCommand nếu clipboard API bị chặn
  }

  try {
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.setAttribute('readonly', '');
    textarea.style.position = 'fixed';
    textarea.style.opacity = '0';
    document.body.appendChild(textarea);
    textarea.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(textarea);
    return ok;
  } catch {
    return false;
  }
}
